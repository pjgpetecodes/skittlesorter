#!/usr/bin/env python3
"""Package only published binaries, never repository configuration or credentials."""
import argparse
import io
import json
import re
import tarfile
from pathlib import Path


def package(publish, output, version, runtime, session_counts):
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Version must contain three numeric components.")
    if runtime not in ("linux-arm", "linux-arm64"):
        raise ValueError("Unsupported runtime.")
    if not (publish / "skittlesorter").is_file():
        raise ValueError("Publish output is missing the Linux app host.")
    files = sorted(publish.rglob("*"))
    for path in files:
        if path.is_symlink() or any(
            name.lower() in ("certs", "secrets") for name in path.relative_to(publish).parts
        ) or path.suffix.lower() in (".key", ".pem", ".pfx", ".p12", ".crt", ".cer", ".csr", ".env") or path.name.lower().startswith("appsettings"):
            raise ValueError(f"Refusing a credential/configuration-bearing publish output: {path.name}")
    output.mkdir(parents=True, exist_ok=True)
    target = output / f"skittlesorter-{version}-{runtime}.tar.gz"
    if target.exists():
        raise FileExistsError(target)
    release = {
        "version": version,
        "runtime": runtime,
        "features": ["session-counts"] if session_counts else [],
    }
    try:
        with tarfile.open(target, "w:gz", format=tarfile.USTAR_FORMAT) as archive:
            for path in files:
                if path.is_dir():
                    continue
                if path.name == "release.json":
                    raise ValueError("release.json is generated by the packager.")
                info = archive.gettarinfo(str(path), arcname=path.relative_to(publish).as_posix())
                info.uid = info.gid = 0
                info.uname = info.gname = ""
                info.mode = 0o755 if path.name == "skittlesorter" else 0o644
                with path.open("rb") as stream:
                    archive.addfile(info, stream)
            data = json.dumps(release, sort_keys=True).encode()
            info = tarfile.TarInfo("release.json")
            info.mode = 0o644
            info.size = len(data)
            archive.addfile(info, io.BytesIO(data))
    except Exception:
        target.unlink(missing_ok=True)
        raise
    print(target)
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--publish", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--runtime", required=True)
    parser.add_argument("--session-counts", choices=["true", "false"], required=True)
    args = parser.parse_args()
    package(args.publish, args.output, args.version, args.runtime, args.session_counts == "true")
